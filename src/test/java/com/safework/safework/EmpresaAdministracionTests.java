package com.safework.safework;

import java.util.List;
import java.util.UUID;
import jakarta.validation.Validation;
import jakarta.validation.ValidatorFactory;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.ValueSource;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.security.access.AccessDeniedException;
import org.springframework.security.authentication.UsernamePasswordAuthenticationToken;
import org.springframework.security.core.authority.SimpleGrantedAuthority;
import org.springframework.security.core.context.SecurityContextHolder;
import org.springframework.security.crypto.bcrypt.BCryptPasswordEncoder;
import com.safework.safework.config.AdministradorPlataformaBootstrap;
import com.safework.safework.model.EmpresaAltaFormulario;
import com.safework.safework.service.EmpresaAdministracionService;
import static org.assertj.core.api.Assertions.*;

/** Transacciones reales JDBC en bases H2 desechables; no conecta a datos locales. */
class EmpresaAdministracionTests {
    private JdbcTemplate jdbc;
    private DataSourceTransactionManager manager;
    private EmpresaAdministracionService empresas;
    private final BCryptPasswordEncoder encoder = new BCryptPasswordEncoder(4);
    private ValidatorFactory validatorFactory;

    @BeforeEach
    void preparar() {
        var ds = new DriverManagerDataSource("jdbc:h2:mem:plataforma_" + UUID.randomUUID() + ";MODE=MySQL;DB_CLOSE_DELAY=-1", "sa", "");
        jdbc = new JdbcTemplate(ds);
        manager = new DataSourceTransactionManager(ds);
        jdbc.execute("CREATE TABLE empresas(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,nombre VARCHAR(150) NOT NULL,codigo VARCHAR(50) UNIQUE NOT NULL,estado VARCHAR(20) NOT NULL,fecha_registro TIMESTAMP NOT NULL)");
        jdbc.execute("CREATE TABLE usuarios(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,username VARCHAR(255) UNIQUE NOT NULL,password VARCHAR(255) NOT NULL,rol VARCHAR(255) NOT NULL,nombre VARCHAR(255) NOT NULL,apellido VARCHAR(255) NOT NULL,correo VARCHAR(255) UNIQUE,estado VARCHAR(255) NOT NULL,fecha_registro TIMESTAMP,empresa_id BIGINT NOT NULL REFERENCES empresas(id))");
        jdbc.update("INSERT INTO empresas(id,nombre,codigo,estado,fecha_registro) VALUES(1,'Principal','principal','ACTIVO',CURRENT_TIMESTAMP)");
        jdbc.execute("ALTER TABLE empresas ALTER COLUMN id RESTART WITH 2");
        validatorFactory = Validation.buildDefaultValidatorFactory();
        empresas = new EmpresaAdministracionService(jdbc, encoder, manager, validatorFactory.getValidator());
        rol("SUPERADMIN");
    }

    @AfterEach
    void limpiar() {
        SecurityContextHolder.clearContext();
        validatorFactory.close();
        jdbc.execute("SHUTDOWN");
    }

    private void rol(String rol) {
        SecurityContextHolder.getContext().setAuthentication(new UsernamePasswordAuthenticationToken(
                "plataforma", "n/a", List.of(new SimpleGrantedAuthority("ROLE_" + rol))));
    }

    private EmpresaAltaFormulario alta() {
        var form = new EmpresaAltaFormulario();
        form.setNombre("Empresa Independiente"); form.setCodigo("independiente");
        form.setAdminUsername("admin.nuevo"); form.setAdminPassword("ClaveUnicaSegura2026!");
        form.setAdminNombre("Ana"); form.setAdminApellido("Prueba"); form.setAdminCorreo("ana@example.invalid");
        return form;
    }

    @ParameterizedTest @ValueSource(strings = {"ADMIN", "SUPERVISOR", "TRABAJADOR"})
    void rolDeEmpresaNoPuedeAdministrarPlataforma(String role) {
        rol(role);
        assertThatThrownBy(() -> empresas.listar()).isInstanceOf(AccessDeniedException.class);
        assertThatThrownBy(() -> empresas.crear(alta())).isInstanceOf(AccessDeniedException.class);
        assertThatThrownBy(() -> empresas.obtener(1L)).isInstanceOf(AccessDeniedException.class);
        assertThatThrownBy(() -> empresas.actualizar(1L, null)).isInstanceOf(AccessDeniedException.class);
    }

    @Test void anonimoNoPuedeListar() {
        SecurityContextHolder.clearContext();
        assertThatThrownBy(() -> empresas.listar()).isInstanceOf(AccessDeniedException.class);
    }

    @Test void altaCreaAdministradorNuevoConHashYEmpresaCorrecta() {
        Long empresa = empresas.crear(alta());
        assertThat(empresa).isGreaterThan(1L);
        assertThat(jdbc.queryForObject("SELECT empresa_id FROM usuarios WHERE username='admin.nuevo'", Long.class)).isEqualTo(empresa);
        assertThat(jdbc.queryForObject("SELECT rol FROM usuarios WHERE username='admin.nuevo'", String.class)).isEqualTo("ADMIN");
        var hash = jdbc.queryForObject("SELECT password FROM usuarios WHERE username='admin.nuevo'", String.class);
        assertThat(hash).isNotEqualTo(alta().getAdminPassword());
        assertThat(encoder.matches(alta().getAdminPassword(), hash)).isTrue();
        assertThat(empresas.listar()).hasSize(2);
    }

    @Test void rechazaUsuarioDuplicadoSinPromoverNiMoverCuentaExistente() {
        var original = empresas.crear(alta());
        var segundo = alta(); segundo.setCodigo("otra-empresa"); segundo.setAdminCorreo("otra@example.invalid");
        assertThatThrownBy(() -> empresas.crear(segundo)).isInstanceOf(IllegalArgumentException.class);
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM empresas", Long.class)).isEqualTo(2L);
        assertThat(jdbc.queryForObject("SELECT empresa_id FROM usuarios WHERE username='admin.nuevo'", Long.class)).isEqualTo(original);
        assertThat(jdbc.queryForObject("SELECT rol FROM usuarios WHERE username='admin.nuevo'", String.class)).isEqualTo("ADMIN");
    }

    @Test void insercionDeAdministradorFallidaRevierteTambienEmpresa() {
        jdbc.execute("ALTER TABLE usuarios ADD CONSTRAINT correo_prohibido CHECK(correo <> 'ana@example.invalid')");
        assertThatThrownBy(() -> empresas.crear(alta())).isInstanceOf(IllegalArgumentException.class);
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM empresas", Long.class)).isEqualTo(1L);
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM usuarios", Long.class)).isZero();
    }

    @Test void editarEstadoNoEliminaCuentasNiCambiaRol() {
        Long empresa = empresas.crear(alta());
        var editar = empresas.obtener(empresa); editar.setEstado("INACTIVO"); editar.setNombre("Nombre Actualizado");
        empresas.actualizar(empresa, editar);
        assertThat(empresas.obtener(empresa).getEstado()).isEqualTo("INACTIVO");
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM usuarios", Long.class)).isEqualTo(1L);
        assertThat(jdbc.queryForObject("SELECT rol FROM usuarios", String.class)).isEqualTo("ADMIN");
    }

    @Test void rechazaClaveCortaYClaveQueSupera72Bytes() {
        var form = alta(); form.setAdminPassword("corta");
        assertThatThrownBy(() -> empresas.crear(form)).isInstanceOf(IllegalArgumentException.class);
        form.setAdminPassword("á".repeat(37));
        assertThatThrownBy(() -> empresas.crear(form)).isInstanceOf(IllegalArgumentException.class);
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM empresas", Long.class)).isEqualTo(1L);
    }

    private AdministradorPlataformaBootstrap bootstrap(String usuario, String password) {
        return new AdministradorPlataformaBootstrap(jdbc, encoder, manager, usuario, password,
                "Responsable", "Plataforma", "responsable@example.invalid");
    }

    @Test void bootstrapExplicitoCreaUnaCuentaYNoSeRepite() {
        bootstrap("dueno.plataforma", "ClaveUnicaSegura2026!").run(null);
        assertThat(jdbc.queryForObject("SELECT rol FROM usuarios WHERE username='dueno.plataforma'", String.class)).isEqualTo("SUPERADMIN");
        assertThatThrownBy(() -> bootstrap("otro.plataforma", "OtraClaveSegura2026!").run(null)).isInstanceOf(IllegalStateException.class);
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM usuarios", Long.class)).isEqualTo(1L);
    }

    @Test void bootstrapNuncaAsciendeUnaCuentaExistente() {
        empresas.crear(alta());
        assertThatThrownBy(() -> bootstrap("admin.nuevo", "OtraClaveSegura2026!").run(null)).isInstanceOf(IllegalStateException.class);
        assertThat(jdbc.queryForObject("SELECT rol FROM usuarios WHERE username='admin.nuevo'", String.class)).isEqualTo("ADMIN");
    }

    @Test void bootstrapSinClaveNoCreaCuentaPredeterminada() {
        assertThatThrownBy(() -> bootstrap("dueno.plataforma", "").run(null)).isInstanceOf(IllegalArgumentException.class);
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM usuarios", Long.class)).isZero();
    }
}
